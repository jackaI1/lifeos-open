export function normalizeBookSearch(value) {
  return String(value).toLowerCase().normalize('NFKD').replace(/\b(first|1st|i)\b/g,'1').replace(/\b(second|2nd|ii)\b/g,'2').replace(/\b(third|3rd|iii)\b/g,'3').replace(/[^a-z0-9]+/g,' ').trim().replace(/\s+/g,' ');
}
export function searchBooks(query) {
  const tokens=normalizeBookSearch(query).split(' ').filter(Boolean);
  return BIBLE_BOOKS.filter(book=>book.searchAliases.some(alias=>tokens.every(token=>normalizeBookSearch(alias).includes(token))));
}
export function selectedPassage(bookId, chapter, chapterEnd = chapter) {
  const book=BIBLE_BOOKS.find(book=>book.canonicalId===bookId);
  if(!book||!Number.isInteger(chapter)||chapter<1||chapter>book.chapterCount||!Number.isInteger(chapterEnd)||chapterEnd<chapter||chapterEnd>book.chapterCount)throw Error('Choose a valid book and chapter.');
  return {bookId:book.canonicalId,chapter,...(chapterEnd>chapter?{chapterEnd}:{}),passage:book.chapterCount===1&&book.omitSingleChapter?book.displayName:book.displayName+' '+chapter+(chapterEnd>chapter?'–'+chapterEnd:'')};
}
const passageAliases=BIBLE_BOOKS.flatMap(book=>book.searchAliases.map(alias=>({book,prefix:normalizeBookSearch(alias)})));
export function parseSelectedPassage(value) {
  const raw=String(value).trim(),range=raw.match(/^(.*?)\s+(\d+)\s*–\s*(\d+)$/);
  if(range){const prefix=normalizeBookSearch(range[1]);for(const {book,prefix:alias} of passageAliases)if(prefix===alias)try{return selectedPassage(book.canonicalId,Number(range[2]),Number(range[3]));}catch{return null;}return null;}
  const normalized=normalizeBookSearch(value);
  for(const {book,prefix} of passageAliases){if(normalized===prefix&&book.chapterCount===1)return selectedPassage(book.canonicalId,1);if(normalized.startsWith(prefix+' ')){const tail=normalized.slice(prefix.length+1);if(/^\d+$/.test(tail)&&String(value).match(/\d+\s*$/))try{return selectedPassage(book.canonicalId,Number(tail));}catch{}}}
  return null;
}
